// Builds lib/travel/fl-zips.ts: the center point of every Florida ZIP code, from the US Census Bureau's ZCTA
// gazetteer file (public domain). Re-run when the Census publishes a new year.
//   1. Download https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2026_Gazetteer/2026_Gaz_zcta_national.zip
//   2. Unzip it, then: node scripts/fl-zip-centroids.mjs <path to 2026_Gaz_zcta_national.txt>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/fl-zip-centroids.mjs <2026_Gaz_zcta_national.txt>");
  process.exit(1);
}
const [header, ...lines] = fs.readFileSync(src, "utf8").trim().split(/\r?\n/);
const cols = header.split("|").map((c) => c.trim());
const [zipCol, latCol, lngCol] = ["GEOID", "INTPTLAT", "INTPTLONG"].map((c) => cols.indexOf(c));
if ([zipCol, latCol, lngCol].includes(-1)) throw new Error(`unexpected columns: ${header}`);

// Florida ZIP codes start with 320–349; keep only points inside Florida's bounding box
const zips = lines
  .map((l) => l.split("|").map((v) => v.trim()))
  .filter((r) => /^3[2-4]\d{3}$/.test(r[zipCol]))
  .map((r) => ({ zip: r[zipCol], lat: Number(r[latCol]), lng: Number(r[lngCol]) }))
  .filter((z) => z.lat > 24.3 && z.lat < 31.1 && z.lng > -87.7 && z.lng < -79.9)
  .sort((a, b) => a.zip.localeCompare(b.zip));
if (zips.length < 900) throw new Error(`only ${zips.length} Florida ZIP codes found`);

const year = path.basename(src).match(/^(\d{4})_/)?.[1] ?? "unknown";
const body = zips.map((z) => `  "${z.zip}": [${z.lat.toFixed(4)}, ${z.lng.toFixed(4)}],`).join("\n");
const out = `// Generated by scripts/fl-zip-centroids.mjs from the US Census Bureau ${year} ZCTA gazetteer (public domain). Don't edit.
import "server-only";

/** Center point [latitude, longitude] of each Florida ZIP code (${zips.length} ZIP Code Tabulation Areas). */
export const FL_ZIP_CENTROIDS: Readonly<Record<string, readonly [number, number]>> = {
${body}
};
`;
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../lib/travel/fl-zips.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${zips.length} Florida ZIP codes to ${path.relative(process.cwd(), target)}`);
